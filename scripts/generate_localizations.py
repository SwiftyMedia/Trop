#!/usr/bin/env python3
"""Generate iOS .strings files from the JSON language sources."""

from __future__ import annotations

import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
LANGUAGES_DIR = ROOT / "languages"
OUTPUT_DIR = ROOT / "Trop" / "Resources"
LOCALE_PATTERN = re.compile(r"^[A-Za-z0-9_-]+$")


def escape_strings_value(value: str) -> str:
    """Escape a JSON value for Apple's .strings format."""

    return (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\r", "\\r")
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )


def read_language(path: Path) -> dict[str, str]:
    with path.open(encoding="utf-8") as language_file:
        values = json.load(language_file)
    if not isinstance(values, dict) or not all(
        isinstance(key, str) and isinstance(value, str)
        for key, value in values.items()
    ):
        raise ValueError(f"{path} must contain a JSON object with string keys and values")
    return values


def render_strings(values: dict[str, str]) -> str:
    lines = ["/* Generated from languages/*.json. Do not edit this file directly. */", ""]
    lines.extend(
        f'"{escape_strings_value(key)}" = "{escape_strings_value(values[key])}";'
        for key in sorted(values)
    )
    return "\n".join(lines) + "\n"


def main() -> None:
    source_path = LANGUAGES_DIR / "en.json"
    if not source_path.is_file():
        raise SystemExit(f"Missing source language: {source_path}")

    source = read_language(source_path)
    language_paths = sorted(LANGUAGES_DIR.glob("*.json"))
    if not language_paths:
        raise SystemExit(f"No language files found in {LANGUAGES_DIR}")

    for language_path in language_paths:
        locale = language_path.stem
        if not LOCALE_PATTERN.fullmatch(locale):
            raise SystemExit(f"Invalid locale filename: {language_path.name}")

        translated = read_language(language_path)
        unknown_keys = sorted(set(translated) - set(source))
        if unknown_keys:
            raise SystemExit(
                f"{language_path.name} contains keys missing from en.json: "
                + ", ".join(unknown_keys)
            )

        missing_keys = sorted(set(source) - set(translated))
        if locale != "en" and missing_keys:
            print(
                f"warning: {language_path.name} is missing {len(missing_keys)} "
                "keys; English fallback will be used"
            )

        values = source | translated
        output_dir = OUTPUT_DIR / f"{locale}.lproj"
        output_dir.mkdir(parents=True, exist_ok=True)
        output_path = output_dir / "Localizable.strings"
        output_path.write_text(render_strings(values), encoding="utf-8")
        print(f"generated {output_path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
